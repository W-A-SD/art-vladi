// Открытие изображения в полном размере
function openImage(src) {
    // Создаем оверлей
    const overlay = document.createElement('div');
    overlay.style.cssText = `
        position: fixed;
        top: 0;
        left: 0;
        width: 100%;
        height: 100%;
        background: rgba(0, 0, 0, 0.95);
        display: flex;
        align-items: center;
        justify-content: center;
        z-index: 10001;
        cursor: pointer;
        animation: fadeIn 0.3s ease-out;
    `;
    
    // Закрытие по клику на фон
    overlay.onclick = function() {
        overlay.remove();
        document.body.style.overflow = 'auto';
    };
    
    // Создаем изображение
    const img = document.createElement('img');
    img.src = src;
    img.style.cssText = `
        max-width: 90%;
        max-height: 90%;
        object-fit: contain;
        border: 2px solid var(--gold);
        border-radius: 5px;
    `;
    
    overlay.appendChild(img);
    document.body.appendChild(overlay);
    document.body.style.overflow = 'hidden';
}

// Закрытие по Escape
document.addEventListener('keydown', function(event) {
    if (event.key === 'Escape') {
        const overlay = document.querySelector('div[style*="z-index: 10001"]');
        if (overlay) {
            overlay.remove();
            document.body.style.overflow = 'auto';
        }
    }
});

// Прокрутка по стрелочкам
function scrollCarousel(btn, direction) {
    const wrapper = btn.closest('.carousel-wrapper');
    const grid = wrapper.querySelector('.courses-grid, .graduates-grid, .reviews-grid');
    if (!grid) return;
    
    const card = grid.querySelector('.course-card, .graduate-card, .review-card');
    if (!card) return;
    
    const cardWidth = card.offsetWidth + 30;
    grid.scrollBy({
        left: cardWidth * direction,
        behavior: 'smooth'
    });
}