// Мобильное меню
function toggleMenu() {
    const menu = document.querySelector('.nav-menu');
    menu.classList.toggle('active');
    
    // Анимация бургера
    const burgerSpans = document.querySelectorAll('.burger span');
    burgerSpans.forEach((span, index) => {
        if (menu.classList.contains('active')) {
            if (index === 0) {
                span.style.transform = 'rotate(45deg) translate(5px, 5px)';
            } else if (index === 1) {
                span.style.opacity = '0';
            } else {
                span.style.transform = 'rotate(-45deg) translate(5px, -5px)';
            }
        } else {
            span.style.transform = 'none';
            span.style.opacity = '1';
        }
    });
}

// Закрытие мобильного меню при клике на ссылку
document.addEventListener('DOMContentLoaded', function() {
    const navLinks = document.querySelectorAll('.nav-menu a');
    navLinks.forEach(link => {
        link.addEventListener('click', function() {
            const menu = document.querySelector('.nav-menu');
            if (menu.classList.contains('active')) {
                toggleMenu();
            }
        });
    });
    
    // Обработка формы
    const form = document.querySelector('.contact-form');
    if (form) {
        form.addEventListener('submit', handleSubmit);
    }
    
    // Анимация при скролле
    window.addEventListener('scroll', revealOnScroll);
    
    // Инициализация анимаций
    revealOnScroll();
});

// Обработка отправки формы
function handleSubmit(event) {
    event.preventDefault();
    
    // Здесь будет логика отправки формы на сервер
    // Для демонстрации показываем уведомление
    
    const form = event.target;
    const formData = new FormData(form);
    const name = formData.get('name') || 'Дорогой гость';
    
    // Создаем уведомление
    showNotification(`Спасибо, ${name}! Мы свяжемся с вами в ближайшее время.`);
    
    // Очищаем форму
    form.reset();
    
    return false;
}

// Функция показа уведомления
function showNotification(message) {
    // Удаляем старые уведомления
    const oldNotification = document.querySelector('.notification');
    if (oldNotification) {
        oldNotification.remove();
    }
    
    // Создаем новое уведомление
    const notification = document.createElement('div');
    notification.className = 'notification';
    notification.textContent = message;
    notification.style.cssText = `
        position: fixed;
        top: 100px;
        right: 20px;
        background-color: var(--gold);
        color: var(--black);
        padding: 20px;
        border-radius: 10px;
        font-weight: 600;
        z-index: 10000;
        animation: slideIn 0.5s ease-out;
        box-shadow: 0 10px 30px rgba(0, 0, 0, 0.3);
        max-width: 350px;
    `;
    
    document.body.appendChild(notification);
    
    // Добавляем стили для анимации
    const style = document.createElement('style');
    style.textContent = `
        @keyframes slideIn {
            from {
                transform: translateX(100%);
                opacity: 0;
            }
            to {
                transform: translateX(0);
                opacity: 1;
            }
        }
    `;
    document.head.appendChild(style);
    
    // Удаляем уведомление через 5 секунд
    setTimeout(() => {
        notification.style.animation = 'slideOut 0.5s ease-in';
        setTimeout(() => {
            notification.remove();
        }, 500);
    }, 5000);
}

// Анимация элементов при скролле
function revealOnScroll() {
    const elements = document.querySelectorAll('.course-card, .advantage-item');
    
    elements.forEach(element => {
        const elementTop = element.getBoundingClientRect().top;
        const elementBottom = element.getBoundingClientRect().bottom;
        const windowHeight = window.innerHeight;
        
        if (elementTop < windowHeight - 100 && elementBottom > 0) {
            element.style.opacity = '1';
            element.style.transform = 'translateY(0)';
        }
    });
}

// Инициализация стилей для анимации скролла
document.addEventListener('DOMContentLoaded', function() {
    const elements = document.querySelectorAll('.course-card, .advantage-item');
    elements.forEach(element => {
        element.style.transition = 'all 0.6s ease-out';
        element.style.opacity = '0';
        element.style.transform = 'translateY(30px)';
    });
    
    // Запускаем проверку видимости
    revealOnScroll();
});

// Плавная прокрутка для всех якорных ссылок
document.addEventListener('DOMContentLoaded', function() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const targetId = this.getAttribute('href');
            if (targetId === '#') return;
            
            const targetElement = document.querySelector(targetId);
            if (targetElement) {
                targetElement.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
});


